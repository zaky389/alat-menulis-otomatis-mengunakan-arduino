def get_char_strokes(char, font_size=4.0, x_offset=0.0, y_offset=0.0):
    """
    Dapatkan stroke path untuk sebuah karakter.

    Args:
        char: Karakter yang akan digambar
        font_size: Ukuran font dalam mm (tinggi karakter)
        x_offset: Offset X (posisi awal horizontal) dalam mm
        y_offset: Offset Y (posisi awal vertikal) dalam mm

    Returns:
        (char_width_mm, strokes): tuple berisi lebar karakter dan list of strokes
        Setiap stroke adalah list of (x_mm, y_mm) dalam milimeter
    """
    if char not in HERSHEY_FONT:
        # Karakter tidak dikenal, gunakan placeholder (kotak)
        char = '?'

    raw_width, raw_strokes = HERSHEY_FONT[char]

    # Skala: font data memiliki tinggi ~21 unit, kita mau font_size mm
    scale = font_size / 21.0

    char_width_mm = raw_width * scale
    scaled_strokes = []

    for stroke in raw_strokes:
        scaled_stroke = []
        for (x, y) in stroke:
            sx = x * scale + x_offset
            sy = y * scale + y_offset
            scaled_stroke.append((sx, sy))
        scaled_strokes.append(scaled_stroke)

    return char_width_mm, scaled_strokes


def get_text_strokes(text, font_size=4.0, letter_spacing=0.8,
                     word_spacing=3.0, line_spacing=7.0,
                     max_width=180.0, x_start=0.0, y_start=0.0):
    """
    Konversi teks menjadi stroke paths dengan word-wrapping.

    Args:
        text: Teks yang akan ditulis
        font_size: Ukuran font (mm)
        letter_spacing: Jarak antar huruf (mm)
        word_spacing: Jarak antar kata (mm)
        line_spacing: Jarak antar baris (mm)
        max_width: Lebar maksimum baris (mm) - untuk word wrap
        x_start: Posisi X awal (mm)
        y_start: Posisi Y awal (mm)

    Returns:
        list of strokes, dimana setiap stroke adalah [(x,y), (x,y), ...]
    """
    all_strokes = []
    cursor_x = x_start
    cursor_y = y_start
    scale = font_size / 21.0

    # Pisahkan teks menjadi baris-baris berdasarkan newline
    lines = text.split('\n')

    for line_text in lines:
        words = line_text.split(' ')
        cursor_x = x_start

        for word_idx, word in enumerate(words):
            # Hitung lebar kata
            word_width = 0
            for ch in word:
                if ch in HERSHEY_FONT:
                    w, _ = HERSHEY_FONT[ch]
                    word_width += w * scale + letter_spacing
                else:
                    word_width += font_size * 0.5 + letter_spacing

            # Word wrap: pindah ke baris baru jika tidak muat
            if cursor_x + word_width > x_start + max_width and cursor_x > x_start:
                cursor_x = x_start
                cursor_y += line_spacing

            # Tulis setiap karakter dalam kata
            for ch in word:
                char_width, char_strokes = get_char_strokes(
                    ch, font_size, cursor_x, cursor_y
                )
                all_strokes.extend(char_strokes)
                cursor_x += char_width + letter_spacing

            # Tambahkan spasi antar kata
            if word_idx < len(words) - 1:
                cursor_x += word_spacing

        # Pindah ke baris baru
        cursor_y += line_spacing
        cursor_x = x_start

    return all_strokes


